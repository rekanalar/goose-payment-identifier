#!/usr/bin/env python3
"""Generate card_brands.goose, the 15 built-in card brands.

Source (read-only input, passed as an argument):
  card-types.ts of credit-card-type 10.3.1
  https://github.com/braintree/credit-card-type/blob/main/src/lib/card-types.ts

Run:
  python3 test/make_brands.py card-types.ts > card_brands.goose

The order of the output is the test order of credit-card-type, which
decides the order of a partial match. A brand holds rows of low, high and
digit count: an exact prefix has low equal to high, and a range has two
different bounds. The script fails when a brand exceeds the inline
capacities (64 rows, 4 gaps, 8 lengths).
"""
import json
import re
import sys

# The order in which credit-card-type tests the brands. creditCardType("")
# returns the brands in this order.
ORDER = ["visa", "mastercard", "american-express", "diners-club", "discover", "troy", "jcb",
         "unionpay", "naranja", "verve", "maestro", "elo", "mir", "hiper", "hipercard"]
ROWS, GAPS, LENGTHS = 64, 4, 8


def arr(block, key, nxt):
    m = re.search(key + r":\s*(\[.*?\]),\s*" + nxt + ":", block, re.S)
    text = re.sub(r",(\s*\])", r"\1", m.group(1))
    return json.loads(text)


def main(path):
    src = open(path, encoding="utf-8").read()
    blocks = {}
    for m in re.finditer(r'\n  "?([a-z-]+)"?: \{\n(.*?)\n  \} as BuiltInCreditCardType,', src, re.S):
        blocks[m.group(1)] = m.group(2)
    if sorted(blocks) != sorted(ORDER):
        sys.exit("brands differ from the expected 15: " + " ".join(sorted(blocks)))
    out = ["// Generated by test/make_brands.py. Do not edit by hand.",
           "// The 15 brands of credit-card-type 10.3.1, in its test order.",
           "namespace payment_identifier;", "", "import std;", "",
           "struct Brand {",
           "    id: const u8[:],",
           "    name: const u8[:],",
           "    patterns: i64[%d]," % (ROWS * 3),
           "    gaps: i64[%d]," % GAPS,
           "    lengths: i64[%d]," % LENGTHS,
           "    code_name: const u8[:],",
           "    code_size: i64,",
           "}", "", "const BUILTIN_BRANDS: Brand[15] = ["]
    for bid in ORDER:
        b = blocks[bid]
        name = re.search(r'niceType:\s*"([^"]*)"', b).group(1)
        pats = arr(b, "patterns", "gaps")
        gaps = arr(b, "gaps", "lengths")
        lens = arr(b, "lengths", "code")
        code = re.search(r'name:\s*"([^"]*)"', b).group(1)
        size = int(re.search(r"size:\s*(\d+)", b).group(1))
        rows = []
        for p in pats:
            lo, hi = (p if isinstance(p, list) else (p, p))
            rows += [lo, hi, len(str(lo))]
        if len(rows) > ROWS * 3 or len(gaps) > GAPS or len(lens) > LENGTHS:
            sys.exit("brand too large: " + bid)
        pad = lambda xs, n: ", ".join(str(x) for x in xs + [0] * (n - len(xs)))
        out.append('    Brand { id: "%s", name: "%s", code_name: "%s", code_size: %d,' % (bid, name, code, size))
        out.append("        gaps: [%s]," % pad(gaps, GAPS))
        out.append("        lengths: [%s]," % pad(lens, LENGTHS))
        out.append("        patterns: [%s] }," % pad(rows, ROWS * 3))
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
