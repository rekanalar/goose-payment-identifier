#!/usr/bin/env python3
"""Generate iban_registry.goose, the country table of the package.

Sources (read-only inputs, passed as arguments):
  iban.dat         the SWIFT IBAN registry release 101, as python-stdnum ships it
                   https://github.com/arthurdejong/python-stdnum/blob/master/stdnum/iban.dat
  schwifty_reg.json, schwifty_over.json
                   generated.json and overwrite.json of schwifty's registry
                   https://github.com/mdomke/schwifty/tree/main/schwifty/registry
  ibantools.ts     the country table of ibantools, for the SEPA flag
                   https://github.com/Simplify/ibantools/blob/master/src/ibantools.ts

Run:
  python3 test/make_registry.py iban.dat schwifty_reg.json schwifty_over.json ibantools.ts > iban_registry.goose

Positions are BBAN-relative with an exclusive end. The overwrite file wins
over the generated file. A country that the registry lists must have a
bank and an account range, or the script fails.
"""
import json
import re
import sys

# Countries with a national BBAN check in the package.
NATIONAL = set("BA BE CZ SK EE ES FR MC HR HU ME MK NO PL PT RS SI FI IS IT SM".split())


def main(dat, reg, over, tools):
    countries = {}
    for line in open(dat, encoding="utf-8"):
        m = re.match(r'^([A-Z]{2}) country="([^"]*)" bban="([^"]*)"', line)
        if m:
            countries[m.group(1)] = (m.group(2), m.group(3))
    if len(countries) != 89:
        sys.exit("expected 89 countries, got %d" % len(countries))
    reg = json.load(open(reg))
    over = json.load(open(over))
    src = open(tools, encoding="utf-8").read()
    sepa = set()
    cur = None
    for line in src.split("\n"):
        m = re.match(r"^  ([A-Z]{2}): \{", line)
        if m:
            cur = m.group(1)
        if cur and "SEPA: true" in line:
            sepa.add(cur)
    if len(sepa & set(countries)) != 37:
        sys.exit("expected 37 SEPA countries, got %d" % len(sepa & set(countries)))
    out = []
    w = out.append
    w("// Generated by test/make_registry.py. Do not edit by hand.")
    w("// SWIFT IBAN registry release 101: 89 countries.")
    w("namespace payment_identifier;")
    w("")
    w("import std;")
    w("")
    w("struct CountrySpec {")
    w("    code: const u8[:],")
    w("    name: const u8[:],")
    w("    iban_length: i64,")
    w("    structure: const u8[:],")
    w("    sepa: bool,")
    w("    bank_start: i64, bank_end: i64,")
    w("    branch_start: i64, branch_end: i64,")
    w("    account_start: i64, account_end: i64,")
    w("    national: i64,")
    w("}")
    w("")
    w("const COUNTRIES: CountrySpec[89] = [")
    for code in sorted(countries):
        name, bban = countries[code]
        pos = dict(reg[code]["positions"])
        pos.update(over.get(code, {}).get("positions", {}))
        if "bank_code" not in pos or "account_code" not in pos:
            sys.exit("no bank or account range for " + code)
        length = sum(int(n) for n in re.findall(r"(\d+)!", bban)) + 4
        if length != reg[code]["iban_length"]:
            sys.exit("length mismatch for " + code)
        b0, b1 = pos["bank_code"]
        r0, r1 = pos.get("branch_code", [0, 0])
        a0, a1 = pos["account_code"]
        w('    CountrySpec { code: "%s", name: "%s", iban_length: %d, structure: "%s", sepa: %s,'
          % (code, name.replace('"', '\\"'), length, bban, "true" if code in sepa else "false"))
        w("        bank_start: %d, bank_end: %d, branch_start: %d, branch_end: %d, account_start: %d, account_end: %d,"
          % (b0, b1, r0, r1, a0, a1))
        w("        national: %d }," % (1 if code in NATIONAL else 0))
    w("];")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
