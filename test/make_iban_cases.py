#!/usr/bin/env python3
"""Generate test/suite/iban_cases.goose, one valid sample IBAN per registry line.

Sources (read-only inputs, passed as arguments):
  test_iban.doctest, test_be_iban.doctest
      https://github.com/arthurdejong/python-stdnum/tree/master/tests
  ibantools_test.js  the test file of ibantools
      https://github.com/Simplify/ibantools/blob/master/test/ibantools.test.js
  iban_registry.goose  the generated table, to check coverage

Run:
  python3 test/make_iban_cases.py test_iban.doctest test_be_iban.doctest ibantools_test.js iban_registry.goose > test/suite/iban_cases.goose

The script keeps every quoted or listed text that has the shape of an IBAN,
passes mod 97-10, has check digits from 02 to 98 and fits the registry length and structure of its country. It adds the registry samples for KW, LC and ST, which
the reference tests lack. It fails when a registry country has no sample.
"""
import re
import sys

EXTRA = ["KW81CBKU0000000000001234560101", "LC55HEMM000100010012001200023015", "ST68000100010051845310112"]


def mod97(s):
    s = s[4:] + s[:4]
    return int("".join(str(int(c, 36)) for c in s)) % 97


def fits(iban, reg):
    """True when the country is in the registry and length and structure match."""
    if iban[:2] not in reg or len(iban) != reg[iban[:2]][0] or not 2 <= int(iban[2:4]) <= 98:
        return False
    rx = "".join({"n": "[0-9]", "a": "[A-Z]", "c": "[A-Z0-9]"}[t] + "{%s}" % n
                 for n, t in re.findall(r"(\d+)!([nac])", reg[iban[:2]][1]))
    return re.fullmatch(rx, iban[4:]) is not None


def main(paths, registry):
    found = set(EXTRA)
    for p in paths:
        text = open(p, encoding="utf-8").read()
        # A line may also hold a print form, such as "MU17 BOMM 0101 ...".
        lines = [re.sub(r"^[.>\s]*", "", ln).replace(" ", "") for ln in text.split("\n")]
        for tok in re.findall(r"\b[A-Z]{2}[0-9]{2}[A-Z0-9]{10,30}\b", text + "\n" + "\n".join(lines)):
            if mod97(tok) == 1:
                found.add(tok)
    reg = {}
    for m in re.finditer(r'CountrySpec \{ code: "([A-Z]{2})".*?iban_length: (\d+), structure: "([^"]*)"', open(registry).read()):
        reg[m.group(1)] = (int(m.group(2)), m.group(3))
    countries = sorted(reg)
    found = {s for s in found if fits(s, reg)}
    have = {s[:2] for s in found}
    missing = [c for c in countries if c not in have]
    if missing:
        sys.exit("no sample for: " + " ".join(missing))
    out = ["// Generated by test/make_iban_cases.py. Do not edit by hand.", "namespace suite;", "",
           "const IBAN_SAMPLES: const u8[:][%d] = [" % len(found)]
    for s in sorted(found):
        out.append('    "%s",' % s)
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(sys.argv[1:4], sys.argv[4])
