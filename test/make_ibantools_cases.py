#!/usr/bin/env python3
"""Generate test/suite/ibantools_cases.goose from the tests of ibantools.

Source (read-only input, passed as an argument):
  ibantools_test.js
  https://github.com/Simplify/ibantools/blob/master/test/ibantools.test.js

Run:
  python3 test/make_ibantools_cases.py ibantools_test.js iban_registry.goose > test/suite/ibantools_cases.goose

The script keeps the one-line checks of isValidIBAN, isValidBIC and
isSEPACountry. Each case records whether the country is in the registry.
ibantools also accepts countries that the registry does not list. For those
countries this package answers false, and the suite expects false.
"""
import re
import sys


def main(tests, registry):
    src = open(tests, encoding="utf-8").read()
    reg = set(re.findall(r'CountrySpec \{ code: "([A-Z]{2})"', open(registry).read()))
    seen = set()
    ibans, bics, sepa = [], [], []
    for m in re.finditer(r"isValidIBAN\('([^']*)'\)\)\.to\.be\.(true|false)", src):
        if (m.group(1), "i") not in seen:
            seen.add((m.group(1), "i"))
            ibans.append((m.group(1), m.group(2) == "true"))
    for m in re.finditer(r"isValidBIC\('([^']*)'\)\)\.to\.be\.(true|false)", src):
        if (m.group(1), "b") not in seen:
            seen.add((m.group(1), "b"))
            bics.append((m.group(1), m.group(2) == "true"))
    for m in re.finditer(r"isSEPACountry\('([^']*)'\)\)\.to\.be\.(true|false)", src):
        sepa.append((m.group(1), m.group(2) == "true"))
    out = ["// Generated by test/make_ibantools_cases.py. Do not edit by hand.", "namespace suite;", "",
           "struct ToolsCase { s: const u8[:], valid: bool, in_registry: bool }", ""]
    for name, rows in (("TOOLS_IBANS", ibans), ("TOOLS_BICS", bics), ("TOOLS_SEPA", sepa)):
        out.append("const %s: ToolsCase[%d] = [" % (name, len(rows)))
        for s, v in rows:
            inreg = (s[:2] in reg) if name == "TOOLS_IBANS" else True
            out.append('    ToolsCase { s: "%s", valid: %s, in_registry: %s },'
                       % (s, "true" if v else "false", "true" if inreg else "false"))
        out.append("];")
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
