#!/usr/bin/env python3
"""Generate test/suite/national_cases.goose: the sample IBANs whose national
BBAN check must fail, although the IBAN check digits are right.

This script is an independent model of the 21 national checks. The rules
follow ibantools (BA BE CZ SK EE ES FR MC HR HU ME MK NO PL PT RS SI) and
schwifty (FI IS IT SM):
  https://github.com/Simplify/ibantools/blob/master/src/ibantools.ts
  https://github.com/mdomke/schwifty/tree/main/schwifty/checksum
For FI, IS, IT and SM the positions are fixed in the code below: FI checks
b[0:13] against b[13], IS weighs b[12:22], IT and SM check b[1:23] against
the letter b[0].

Run:
  python3 test/make_national_cases.py test/suite/iban_cases.goose > test/suite/national_cases.goose
"""
import re
import sys

def mod9710(s):
    # ibantools chunked version
    while len(s)>2:
        part=s[:6]; v=int(part)
        s=str(v%97)+s[6:]
    return int(s)%97

def be_check(b):
    chk=int(b[:-2]); cs=int(b[-2:]); r=chk%97
    return cs==(97 if r==0 else r)

def czsk(b):
    wp=[10,5,8,4,2,1]; ws=[6,3,7,9,10,5,8,4,2,1]
    pre=b[4:9]; suf=b[10:19]
    s=sum(int(c)*w for c,w in zip(pre,wp))
    r=s%11; exp=0 if r==0 else (1 if r==1 else 11-r)
    if exp!=int(b[9]): return False
    s=sum(int(c)*w for c,w in zip(suf,ws))
    r=s%11; exp=0 if r==0 else (1 if r==1 else 11-r)
    return exp==int(b[19])

def ee_check(b):
    w=[7,1,3,7,1,3,7,1,3,7,1,3,7]
    s=sum(int(c)*x for c,x in zip(b[2:15],w))
    r=s%10
    return int(b[15])==(0 if r==0 else 10-r)

def es_check(b):
    wb=[4,8,5,10,9,7,3,6]; wa=[1,2,4,8,5,10,9,7,3,6]
    s=sum(int(c)*w for c,w in zip(b[0:8],wb)); r=s%11
    if int(b[8])!=(0 if r==0 else (1 if r==1 else 11-r)): return False
    s=sum(int(c)*w for c,w in zip(b[10:20],wa)); r=s%11
    return int(b[9])==(0 if r==0 else (1 if r==1 else 11-r))

def fr_map(s):
    out=[]
    for c in s:
        o=ord(c)
        if o<65: out.append(c); continue
        m={65:49,74:49,66:50,75:50,83:50,67:51,76:51,84:51,68:52,77:52,85:52,69:53,78:53,86:53,70:54,79:54,87:54,71:55,80:55,88:55,72:56,81:56,89:56,73:57,82:57,90:57}
        out.append(chr(m[o]))
    return ''.join(out)

def fr_check(b): return mod9710(fr_map(b))==0

def mod1110(s, control):
    nr=10
    for ch in s:
        nr+=int(ch)
        if nr%10!=0: nr=nr%10
        nr=nr*2; nr=nr%11
    return control==(0 if 11-nr==10 else 11-nr)

def hr_check(b): return mod1110(b[0:6],int(b[6])) and mod1110(b[7:16],int(b[16]))

def hu_check(b):
    w=[9,7,3,1,9,7,3,1,9,7,3,1,9,7,3]
    s=sum(int(c)*x for c,x in zip(b[0:7],w)); r=s%10
    if int(b[7])!=(0 if r==0 else 10-r): return False
    if b.endswith('00000000'):
        s=sum(int(c)*x for c,x in zip(b[8:15],w)); r=s%10
        return int(b[15])==(0 if r==0 else 10-r)
    s=sum(int(c)*x for c,x in zip(b[8:23],w)); r=s%10
    return int(b[23])==(0 if r==0 else 10-r)

def no_check(b):
    w=[5,4,3,2,7,6,5,4,3,2]
    s=sum(int(c)*x for c,x in zip(b[0:10],w)); r=s%11
    return int(b[10])==(0 if r==0 else 11-r)

def pl_check(b):
    w=[3,9,7,1,3,9,7]
    s=sum(int(c)*x for c,x in zip(b[0:7],w)); r=s%10
    return int(b[7])==(0 if r==0 else 10-r)

def mod97_bban(b): return mod9710(b)==1

def fi_check(b):
    # schwifty FI: luhn over bank_code + account_code (positions)
    comp=b[0:13]
    val=luhn_digit(comp)
    return val==b[13]

def luhn_digit(value):
    numerical=''.join(str(ord(c)-55) if c.isalpha() else c for c in value)
    processed=''.join(str((2-i%2)*int(n)) for i,n in enumerate(reversed(numerical)))
    return str((10-sum(int(n) for n in processed))%10)

def is_check(b):
    ahid=b[12:22]
    w=[3,2,7,6,5,4,3,2]
    s=sum(int(c)*x for c,x in zip(ahid,w))%11
    return str(0 if s==0 else 11-s)==ahid[8]

CHAR={str(i):i for i in range(10)}
for i,c in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'): CHAR[c]=i
ODDS=(1,0,5,7,9,13,15,17,19,21,2,4,18,20,11,3,6,8,12,14,16,10,22,25,24,23)
def it_check(b):
    comp=b[1:23]
    s=0
    for i,ch in enumerate(comp):
        v=CHAR[ch]
        s+= v if (i+1)%2==0 else ODDS[v]
    return chr(65+s%26)==b[0]

CHECKS={'BA':mod97_bban,'BE':be_check,'CZ':czsk,'SK':czsk,'EE':ee_check,'ES':es_check,'FR':fr_check,'MC':fr_check,
 'HR':hr_check,'HU':hu_check,'NO':no_check,'PL':pl_check,'ME':mod97_bban,'MK':mod97_bban,'PT':mod97_bban,
 'RS':mod97_bban,'SI':mod97_bban,'FI':fi_check,'IS':is_check,'IT':it_check,'SM':it_check}


def main(path):
    samples = re.findall(r'^    "([A-Z0-9]+)",$', open(path).read(), re.M)
    bad = []
    for s in samples:
        cc, b = s[:2], s[4:]
        if cc in CHECKS and not CHECKS[cc](b):
            bad.append(s)
    print("// Generated by test/make_national_cases.py. Do not edit by hand.")
    print("namespace suite;")
    print("")
    print("// Sample IBANs with right check digits whose national check fails.")
    print("const NATIONAL_BAD_SAMPLES: const u8[:][%d] = [" % len(bad))
    for s in bad:
        print('    "%s",' % s)
    print("];")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
